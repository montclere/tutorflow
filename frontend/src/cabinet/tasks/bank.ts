export function bankByNumber(exam: string, number: number): TaskItem[] {
  return bankTasks.filter((task) => task.exam === exam && task.number === number);
}

export function countByNumber(exam: string): Map<number, number> {
  const counts = new Map<number, number>();
  for (const task of bankTasks) if (task.exam === exam && task.number !== undefined) counts.set(task.number, (counts.get(task.number) ?? 0) + 1);
  return counts;
}
